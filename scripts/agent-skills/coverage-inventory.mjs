#!/usr/bin/env node
import assert from 'node:assert/strict'
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'
import { validateReviewResult } from './lib.mjs'

const repository = new URL('../../', import.meta.url)
export const coverageSamples = Object.freeze(['forward', 'heldout', 'heldout2', 'heldout3'])

export function coverageInventory({ root = repository } = {}) {
  const json = (name) => JSON.parse(fs.readFileSync(new URL(name, root), 'utf8'))
  const catalog = json('config/agent-skills/catalog.yaml')
  const labels = Object.fromEntries(
    coverageSamples.map((name) => [name, json(`docs/agent-skills/${name}-labels.json`)]),
  )
  const skills = catalog.skills.map(({ id, entrypoint, codexLink, capabilities }) => {
    const link = new URL(codexLink, root)
    assert.ok(fs.existsSync(new URL(entrypoint, root)), `missing canonical source: ${id}`)
    assert.ok(fs.lstatSync(link).isSymbolicLink(), `not a Codex symlink: ${id}`)
    const relativeTarget = fs.readlinkSync(link)
    assert.equal(path.isAbsolute(relativeTarget), false, `absolute Codex link: ${id}`)
    assert.equal(
      fs.realpathSync(link),
      fs.realpathSync(new URL('.', new URL(entrypoint, root))),
      `Codex link differs from canonical source: ${id}`,
    )
    const fixture = `tests/agent-skills/fixtures/${id}.json`
    const exists = fs.existsSync(new URL(fixture, root))
    const result = exists ? json(fixture).reviewResult : null
    const errors = result ? validateReviewResult(result) : ['missing reviewResult']
    if (result && result.skill !== id) errors.push('example belongs to another skill')
    return {
      skill: id,
      canonicalSource: entrypoint,
      codexLink,
      relativeTarget,
      capabilities,
      example: result ? `${fixture}#reviewResult` : null,
      exampleErrors: errors,
      samples: Object.fromEntries(
        coverageSamples.map((name) => [
          name,
          labels[name].cases
            .filter(({ expected }) => expected.some(({ skill }) => skill === id))
            .map(({ number }) => number),
        ]),
      ),
    }
  })
  const noPositives = (names) =>
    skills
      .filter(({ samples }) => names.every((name) => samples[name].length === 0))
      .map(({ skill }) => skill)
  return {
    schemaVersion: 1,
    skills,
    gaps: {
      missingOrInvalidExamples: skills
        .filter(({ exampleErrors }) => exampleErrors.length)
        .map(({ skill }) => skill),
      noPositiveBeforeHeldout3: noPositives(coverageSamples.slice(0, 3)),
      noPositiveAcrossAllSamples: noPositives(coverageSamples),
    },
  }
}

export function renderCoverageInventory(inventory) {
  const names = (values) => (values.length ? values.join(', ') : 'none')
  return [
    '# Registered skill coverage inventory',
    '',
    'Classification: internal project documentation. Generated by `node scripts/agent-skills/coverage-inventory.mjs`; `--check` rejects drift. Positive labels are expected review scopes, not proof of advice quality or of every listed capability.',
    '',
    '| Skill | Canonical source | Codex link → relative target | Capabilities | Persisted example | v1 five | heldout | heldout2 | heldout3 |',
    '| --- | --- | --- | --- | --- | --- | --- | --- | --- |',
    ...inventory.skills.map(
      (row) =>
        `| ${row.skill} | \`${row.canonicalSource}\` | \`${row.codexLink}\` → \`${row.relativeTarget}\` | ${row.capabilities.join(', ')} | ${row.example ? `\`${row.example}\`` : 'MISSING'} | ${coverageSamples.map((sample) => names(row.samples[sample].map((n) => `#${n}`))).join(' | ')} |`,
    ),
    '',
    `Registered skills: ${inventory.skills.length}. Missing or invalid persisted examples: ${names(inventory.gaps.missingOrInvalidExamples)}.`,
    '',
    `No positive label before heldout3: ${names(inventory.gaps.noPositiveBeforeHeldout3)}.`,
    '',
    `No positive label across all four samples: ${names(inventory.gaps.noPositiveAcrossAllSamples)}. These are open coverage gaps, not approved exceptions or zero-error recall claims.`,
    '',
    'The two new examples identify themselves as synthetic. Their timestamps record example creation, their IDs begin with synthetic-, and their source SHA is context only. They attest no review, command execution, dispatch or ingestion. Existing examples retain their original provenance.',
    '',
    'Actual prior advice envelopes remain in `docs/agent-skills/advice-v2-review.json` with their existing identities, timestamps, reviewed SHAs and per-skill evidence. `forward-blind-review.json` is an older partial advice bundle, not a complete result envelope; no invented historical envelope is added. This coverage exercise performs routing only and creates no new actual review identities.',
    '',
  ].join('\n')
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  try {
    const args = process.argv.slice(2)
    assert.ok(
      args.length === 0 || (args.length === 1 && args[0] === '--check'),
      'usage: coverage-inventory.mjs [--check]',
    )
    const inventory = coverageInventory()
    const content = renderCoverageInventory(inventory)
    const target = new URL('docs/agent-skills/coverage-inventory.md', repository)
    if (args.includes('--check'))
      assert.equal(fs.readFileSync(target, 'utf8'), content, 'stale coverage inventory')
    else fs.writeFileSync(fileURLToPath(target), content)
    assert.deepEqual(inventory.gaps.missingOrInvalidExamples, [], 'persisted example gaps')
    console.log(JSON.stringify(inventory.gaps, null, 2))
  } catch (error) {
    console.error(error.message)
    process.exitCode = 1
  }
}
